CREATE TABLE chapter_generation_evaluation_reports (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    work_id BIGINT NOT NULL,
    chapter_id BIGINT NOT NULL,
    generation_id BIGINT NOT NULL,
    generation_scene_id BIGINT NULL,
    context_snapshot_id BIGINT NULL,
    ai_task_id BIGINT NULL,
    agent_run_id BIGINT NULL,
    idempotency_key VARCHAR(128) NOT NULL,
    input_fingerprint CHAR(64) NOT NULL,
    source_snapshot_json JSON NOT NULL,
    report_status VARCHAR(32) NOT NULL,
    conclusion VARCHAR(32) NULL,
    findings_json JSON NULL,
    ruleset_version VARCHAR(64) NOT NULL,
    evaluator_version VARCHAR(64) NOT NULL,
    revision_attempt INT NOT NULL DEFAULT 0,
    revision_candidate_id BIGINT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    gmt_create DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uk_generation_evaluation_idempotency (generation_id, idempotency_key),
    KEY idx_generation_evaluation_generation_status (generation_id, report_status, id),
    KEY idx_generation_evaluation_scene (generation_scene_id, id),
    CONSTRAINT fk_generation_evaluation_generation FOREIGN KEY (generation_id) REFERENCES chapter_generations (id),
    CONSTRAINT fk_generation_evaluation_scene FOREIGN KEY (generation_scene_id) REFERENCES chapter_generation_scenes (id),
    CONSTRAINT fk_generation_evaluation_snapshot FOREIGN KEY (context_snapshot_id) REFERENCES story_context_snapshots (id),
    CONSTRAINT fk_generation_evaluation_task FOREIGN KEY (ai_task_id) REFERENCES ai_tasks (id),
    CONSTRAINT fk_generation_evaluation_run FOREIGN KEY (agent_run_id) REFERENCES agent_runs (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;

CREATE TABLE chapter_generation_revision_candidates (
    id BIGINT NOT NULL AUTO_INCREMENT PRIMARY KEY,
    report_id BIGINT NOT NULL,
    generation_id BIGINT NOT NULL,
    generation_scene_id BIGINT NULL,
    source_scene_id BIGINT NULL,
    candidate_status VARCHAR(32) NOT NULL,
    revision_content LONGTEXT NULL,
    evidence_range_json JSON NOT NULL,
    source_fingerprint CHAR(64) NOT NULL,
    deleted TINYINT NOT NULL DEFAULT 0,
    version INT NOT NULL DEFAULT 0,
    gmt_create DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    gmt_modified DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    KEY idx_generation_revision_report (report_id, candidate_status),
    KEY idx_generation_revision_generation (generation_id, generation_scene_id),
    CONSTRAINT fk_generation_revision_report FOREIGN KEY (report_id) REFERENCES chapter_generation_evaluation_reports (id),
    CONSTRAINT fk_generation_revision_generation FOREIGN KEY (generation_id) REFERENCES chapter_generations (id),
    CONSTRAINT fk_generation_revision_scene FOREIGN KEY (generation_scene_id) REFERENCES chapter_generation_scenes (id),
    CONSTRAINT fk_generation_revision_source FOREIGN KEY (source_scene_id) REFERENCES chapter_generation_scenes (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_0900_ai_ci;
